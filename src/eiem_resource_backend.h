// AnimeStudio's Unity asset reader and the native game both use Unity's
// Y-up, left-handed mesh basis.  The earlier experimental package marker
// called this Z-up and the runtime rotated vertices/bindposes on every load;
// that mixed the mesh basis with the live bone palette and produced twisting.
// The package already stores native mesh data and bindposes in the exact
// basis consumed by SkinnedMeshRenderer. Preserve the marker as metadata;
// there is no coordinate conversion at this runtime boundary.

class EiemNativeReader {
 public:
  explicit EiemNativeReader(const char *path) : input_(EiemOpenUtf8Input(path)) {}

  bool Good() const { return input_.good(); }
  bool End() { return input_.peek() == std::char_traits<char>::eof(); }

  bool Bytes(void *out, size_t count) {
    if (!out || count == 0) return count == 0;
    input_.read((char *)out, (std::streamsize)count);
    return input_.good();
  }

  template <typename T>
  bool Value(T *out) {
    return Bytes(out, sizeof(T));
  }

  bool String(std::string *out) {
    if (!out) return false;
    uint32_t length = 0;
    for (int shift = 0; shift <= 28; shift += 7) {
      uint8_t byte = 0;
      if (!Value(&byte)) return false;
      length |= (uint32_t)(byte & 0x7f) << shift;
      if (!(byte & 0x80)) break;
      if (shift == 28) return false;
    }
    if (length > 4 * 1024 * 1024) return false;
    out->resize(length);
    return !length || Bytes(out->data(), length);
  }

  bool Count(uint32_t *out, uint32_t maximum = 100000000) {
    int32_t value = 0;
    if (!Value(&value) || value < 0 || (uint32_t)value > maximum) return false;
    *out = (uint32_t)value;
    return true;
  }

  bool Skip(size_t count) {
    if (count > (size_t)(std::numeric_limits<std::streamoff>::max)()) return false;
    input_.seekg((std::streamoff)count, std::ios::cur);
    return input_.good();
  }

 private:
  std::ifstream input_;
};

static bool EiemReadFloatArray(EiemNativeReader &reader,
                               std::vector<float> *out) {
  uint32_t count = 0;
  if (!reader.Count(&count)) return false;
  out->resize(count);
  return !count || reader.Bytes(out->data(), (size_t)count * sizeof(float));
}

static bool EiemReadUvChannel(EiemNativeReader &reader,
                              EiemNativeUvChannel *out,
                              int32_t vertexCount) {
  std::vector<float> values;
  if (!out || !EiemReadFloatArray(reader, &values)) return false;
  if (values.empty()) return true;
  if (vertexCount <= 0 || values.size() % (size_t)vertexCount) return false;
  const size_t dimensions = values.size() / (size_t)vertexCount;
  out->dimensions = (int32_t)dimensions;
  if (dimensions == 2) {
    out->values2.resize((size_t)vertexCount);
    memcpy(out->values2.data(), values.data(), values.size() * sizeof(float));
  } else if (dimensions == 3) {
    out->values3.resize((size_t)vertexCount);
    memcpy(out->values3.data(), values.data(), values.size() * sizeof(float));
  } else if (dimensions == 4) {
    out->values4.resize((size_t)vertexCount);
    memcpy(out->values4.data(), values.data(), values.size() * sizeof(float));
  } else {
    return false;
  }
  return true;
}

template <typename T>
static bool EiemReadTypedFloatArray(EiemNativeReader &reader,
                                    std::vector<T> *out, uint32_t components,
                                    int32_t vertexCount) {
  std::vector<float> values;
  if (!EiemReadFloatArray(reader, &values)) return false;
  if (values.empty()) {
    out->clear();
    return true;
  }
  if (vertexCount < 0 || values.size() != (size_t)vertexCount * components ||
      sizeof(T) != components * sizeof(float))
    return false;
  out->resize((size_t)vertexCount);
  memcpy(out->data(), values.data(), values.size() * sizeof(float));
  return true;
}

static bool EiemReadBlendShapes(EiemNativeReader &reader,
                                EiemNativeMeshDocument *out) {
  uint32_t count = 0;
  if (!out || !reader.Count(&count, 10000000)) return false;
  out->blendShapeVertices.resize(count);
  for (auto &vertex : out->blendShapeVertices) {
    if (!reader.Value(&vertex.index) || !reader.Value(&vertex.vertex) ||
        !reader.Value(&vertex.normal) || !reader.Value(&vertex.tangent))
      return false;
  }
  if (!reader.Count(&count, 1000000)) return false;
  out->blendShapeFrames.resize(count);
  for (uint32_t i = 0; i < count; ++i) {
    auto &frame = out->blendShapeFrames[i];
    uint8_t hasNormals = 0, hasTangents = 0, hasAdditionalNormals = 0;
    if (!reader.String(&frame.name) || !reader.Value(&frame.firstVertex) ||
        !reader.Value(&frame.vertexCount) || !reader.Value(&hasNormals) ||
        !reader.Value(&hasTangents) || !reader.Value(&hasAdditionalNormals) ||
        (uint64_t)frame.firstVertex + frame.vertexCount >
            out->blendShapeVertices.size())
      return false;
    frame.hasNormals = hasNormals != 0;
    frame.hasTangents = hasTangents != 0;
    frame.hasAdditionalNormals = hasAdditionalNormals != 0;
  }
  if (!reader.Count(&count, 1000000)) return false;
  out->blendShapeChannels.resize(count);
  for (uint32_t i = 0; i < count; ++i) {
    auto &channel = out->blendShapeChannels[i];
    if (!reader.String(&channel.name) || !reader.Value(&channel.nameHash) ||
        !reader.Value(&channel.frameIndex) || !reader.Value(&channel.frameCount) ||
        (uint64_t)channel.frameIndex + channel.frameCount >
            out->blendShapeFrames.size())
      return false;
  }
  if (!EiemReadFloatArray(reader, &out->blendShapeWeights) ||
      out->blendShapeWeights.size() != out->blendShapeFrames.size() ||
      !reader.Count(&count, 10000000))
    return false;
  return reader.Skip((size_t)count * sizeof(float) * 3);
}

static bool EiemReadNativeMesh(const char *path, EiemNativeMeshDocument *out,
                               char *error, size_t errorSize) {
  if (error && errorSize) error[0] = '\0';
  if (!path || !out) return false;
  EiemNativeReader reader(path);
  char magic[8] = {};
  int32_t version = 0;
  if (!reader.Good() || !reader.Bytes(magic, sizeof(magic)) ||
      memcmp(magic, "EFFMESH\0", sizeof(magic)) != 0 || !reader.Value(&version) ||
      version != 6 ||
      !reader.String(&out->coordinateSpace) ||
      !reader.String(&out->source) || !reader.String(&out->name) ||
      !reader.Value(&out->vertexCount) || out->vertexCount < 0 ||
      out->vertexCount > 10000000 ||
      !EiemReadTypedFloatArray(reader, &out->vertices, 3, out->vertexCount) ||
      !EiemReadTypedFloatArray(reader, &out->normals, 3, out->vertexCount) ||
      !EiemReadTypedFloatArray(reader, &out->tangents, 4, out->vertexCount) ||
      !EiemReadTypedFloatArray(reader, &out->colors, 4, out->vertexCount)) {
    if (error) strncpy_s(error, errorSize, "Expected EFFMESH v6; re-export with current EFF tools, or check vertex channels", _TRUNCATE);
    return false;
  }
  for (size_t channel = 0; channel < _countof(out->uvs); ++channel) {
    if (!EiemReadUvChannel(reader, &out->uvs[channel], out->vertexCount)) {
      if (error) strncpy_s(error, errorSize, "Invalid EFF UV channel", _TRUNCATE);
      return false;
    }
  }
  uint32_t count = 0;
  if (!reader.Count(&count) || count > 300000000) goto invalid;
  out->indices.resize(count);
  if (count && !reader.Bytes(out->indices.data(), (size_t)count * sizeof(uint32_t))) goto invalid;
  if (!reader.Count(&count, 1024)) goto invalid;
  out->subMeshes.resize(count);
  for (auto &subMesh : out->subMeshes) {
    if (!reader.Value(&subMesh.topology) || !reader.Value(&subMesh.indexStart) ||
        !reader.Value(&subMesh.indexCount) || !reader.Value(&subMesh.baseVertex) ||
        !reader.Value(&subMesh.firstVertex) || !reader.Value(&subMesh.vertexCount) ||
        subMesh.topology != 0 ||
        (uint64_t)subMesh.indexStart + subMesh.indexCount > out->indices.size())
      goto invalid;
  }
  if (!reader.Count(&count, 10000000)) goto invalid;
  out->skin.resize(count);
  if (count && !reader.Bytes(out->skin.data(), (size_t)count * sizeof(BoneWeight))) goto invalid;
  if (!out->skin.empty() && out->skin.size() != out->vertices.size()) goto invalid;
  if (!reader.Count(&count, 10000000)) goto invalid;
  out->bindPoses.resize(count);
  if (count && !reader.Bytes(out->bindPoses.data(), (size_t)count * sizeof(Matrix4x4))) goto invalid;
  if (!reader.Count(&count, 10000000)) goto invalid;
  out->boneHashes.resize(count);
  if (count && !reader.Bytes(out->boneHashes.data(), (size_t)count * sizeof(uint32_t))) goto invalid;

  if (!reader.Count(&count, 1000000)) goto invalid;
  out->bonePaths.resize(count);
  for (auto &path : out->bonePaths) {
    if (!reader.String(&path)) goto invalid;
  }
  if (!out->bonePaths.empty() &&
      out->bonePaths.size() != out->bindPoses.size())
    goto invalid;

  if (!reader.Count(&count, 1000000)) goto invalid;
  out->boneIndexPaths.resize(count);
  for (auto &path : out->boneIndexPaths) {
    if (!reader.String(&path)) goto invalid;
  }
  if (!out->boneIndexPaths.empty() &&
      out->boneIndexPaths.size() != out->bindPoses.size())
    goto invalid;

  if (!reader.Count(&count, 1000000)) goto invalid;
  out->boneSources.resize(count);
  for (auto &source : out->boneSources) {
    if (!reader.String(&source.meshPath) || !reader.String(&source.meshAsset) ||
        !reader.Value(&source.slot)) goto invalid;
  }
  if (!out->boneSources.empty() &&
      out->boneSources.size() != out->bindPoses.size()) goto invalid;

  if (!reader.Count(&count, 1000000) || count != out->bindPoses.size())
    goto invalid;
  out->boneSourceCandidates.resize(count);
  for (auto &candidates : out->boneSourceCandidates) {
    uint32_t candidateCount = 0;
    // A zero-candidate slot is valid for a Mod-owned Skeleton bone. Native
    // slots are resolved through the instance's original Renderer palettes;
    // Mod-owned slots are supplied by the optional Skeleton resource at bind
    // time.
    if (!reader.Count(&candidateCount, 1024))
      goto invalid;
    candidates.resize(candidateCount);
    for (auto &source : candidates) {
      if (!reader.String(&source.meshPath) ||
          !reader.String(&source.meshAsset) || !reader.Value(&source.slot))
        goto invalid;
    }
  }

  if (!EiemReadBlendShapes(reader, out) || !reader.End()) goto invalid;
  if (out->vertices.size() != (size_t)out->vertexCount || out->subMeshes.empty()) goto invalid;
  return true;

invalid:
  if (error) strncpy_s(error, errorSize, "Invalid or unsupported EFF mesh payload", _TRUNCATE);
  return false;
}

