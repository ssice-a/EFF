static int64_t EiemReadNativeMeshScalar(void *method, void *mesh,
                                        bool isBoolean = false) {
  if (!method || !mesh || !il2cpp_object_unbox) return -1;
  void *boxed = EiemBackendInvokeNoThrow(method, mesh);
  if (!boxed) return -1;
  void *value = il2cpp_object_unbox(boxed);
  if (!value) return -1;
  int32_t result = -1;
  __try {
    if (isBoolean) {
      uint8_t boolean = 0;
      memcpy(&boolean, value, sizeof(boolean));
      result = boolean ? 1 : 0;
    } else {
      memcpy(&result, value, sizeof(result));
    }
  }
  __except (EXCEPTION_EXECUTE_HANDLER) { return -1; }
  return result;
}

static uintptr_t EiemReadNativePointerField(uintptr_t base, size_t offset) {
  if (!base) return 0;
  uintptr_t value = 0;
  __try { value = *(const uintptr_t *)(base + offset); }
  __except (EXCEPTION_EXECUTE_HANDLER) { value = 0; }
  return value;
}

static int64_t EiemReadNativeInt32Field(uintptr_t base, size_t offset) {
  if (!base) return -1;
  int32_t value = -1;
  __try { value = *(const int32_t *)(base + offset); }
  __except (EXCEPTION_EXECUTE_HANDLER) { value = -1; }
  return value;
}

__declspec(noinline) static void *EiemGetNativeMeshPointer(void *mesh) {
  if (!mesh || !s_eiemMeshHGGetPtrUnchecked || !il2cpp_object_unbox)
    return nullptr;
  void *boxed = EiemBackendInvokeNoThrow(s_eiemMeshHGGetPtrUnchecked, mesh);
  void *value = boxed ? il2cpp_object_unbox(boxed) : nullptr;
  uintptr_t native = 0;
  if (value) {
    __try { memcpy(&native, value, sizeof(native)); }
    __except (EXCEPTION_EXECUTE_HANDLER) { native = 0; }
  }
  return reinterpret_cast<void *>(native);
}

// UnityPlayer's Mesh vtable entry +0x10 is the exact post-deserialization
// finalizer selected by sub_180464780 after sub_1800BE670 returns.  On the
// current Endfield player it is sub_1800D58A0, which dispatches to
// sub_18019BD80 and then completes the native resource registration.  Keep the
// check against both the vtable and target RVA so a game update cannot turn a
// harmless optimization into an arbitrary call through a changed ABI.
static bool EiemFinalizeNativeMeshWithGamePipeline(void *mesh,
                                                    const char *path) {
  if (!mesh || !EiemOnUnityThread()) {
    Log("[MESH-META-FINALIZE-SKIP] mesh=%p reason=%s path=%s",
        mesh, mesh ? "not-on-unity-thread" : "null-mesh",
        path ? path : "<none>");
    return false;
  }
  void *nativeObject = EiemGetNativeMeshPointer(mesh);
  if (!nativeObject) {
    Log("[MESH-META-FINALIZE-SKIP] mesh=%p reason=native-pointer-null path=%s",
        mesh, path ? path : "<none>");
    return false;
  }

  HMODULE unity = GetModuleHandleW(L"UnityPlayer.dll");
  const uintptr_t base = reinterpret_cast<uintptr_t>(unity);
  uintptr_t vtable = 0;
  uintptr_t finalize = 0;
  __try {
    vtable = *reinterpret_cast<const uintptr_t *>(nativeObject);
    finalize = vtable ? *reinterpret_cast<const uintptr_t *>(vtable + 0x10)
                      : 0;
  } __except (EXCEPTION_EXECUTE_HANDLER) {
    Log("[MESH-META-FINALIZE-SKIP] mesh=%p native=%p reason=vtable-read-seh "
        "path=%s", mesh, nativeObject, path ? path : "<none>");
    return false;
  }
  const uintptr_t vtableRva = base && vtable >= base ? vtable - base : 0;
  const uintptr_t finalizeRva = base && finalize >= base ? finalize - base : 0;
  if (!base || vtableRva != 0x19C8230 || finalizeRva != 0xD58A0) {
    Log("[MESH-META-FINALIZE-SKIP] mesh=%p native=%p reason=unity-layout-mismatch "
        "vtable=%p rva=0x%llX finalize=%p rva=0x%llX path=%s",
        mesh, nativeObject, (void *)vtable,
        (unsigned long long)vtableRva, (void *)finalize,
        (unsigned long long)finalizeRva, path ? path : "<none>");
    return false;
  }
  using NativeFinalizeFn = uintptr_t(__fastcall *)(uintptr_t);
  bool completed = false;
  uintptr_t result = 0;
  __try {
    result = reinterpret_cast<NativeFinalizeFn>(finalize)(
        reinterpret_cast<uintptr_t>(nativeObject));
    completed = true;
  } __except (EXCEPTION_EXECUTE_HANDLER) {
    Log("[MESH-META-FINALIZE-FAIL] mesh=%p native=%p reason=game-finalizer-seh "
        "path=%s", mesh, nativeObject, path ? path : "<none>");
    return false;
  }
  Log("[MESH-META-FINALIZE] mesh=%p native=%p entry=%p result=%p path=%s",
      mesh, nativeObject, (void *)finalize, (void *)result,
      path ? path : "<none>");
  return completed;
}

static bool EiemUnityRvaIsMapped(HMODULE module, uintptr_t rva,
                                 size_t bytes = 1) {
  if (!module) return false;
  __try {
    auto *base = reinterpret_cast<const uint8_t *>(module);
    const auto *dos = reinterpret_cast<const IMAGE_DOS_HEADER *>(base);
    if (dos->e_magic != IMAGE_DOS_SIGNATURE || dos->e_lfanew <= 0)
      return false;
    const auto *nt = reinterpret_cast<const IMAGE_NT_HEADERS *>(
        base + dos->e_lfanew);
    if (nt->Signature != IMAGE_NT_SIGNATURE ||
        nt->OptionalHeader.SizeOfImage == 0)
      return false;
    const size_t imageSize = nt->OptionalHeader.SizeOfImage;
    return rva < imageSize && bytes <= imageSize - rva;
  }
  __except (EXCEPTION_EXECUTE_HANDLER) { return false; }
}

// EFFMESH stores the fixed BoneWeight layout, including zero-weight slots.
// The number of positive influences on one vertex is not this layout width.
static constexpr int32_t kEiemBoneWeightSlotCount =
    (int32_t)(sizeof(BoneWeight) / (sizeof(float) + sizeof(int32_t)));
static_assert(sizeof(BoneWeight) ==
                  4 * sizeof(float) + 4 * sizeof(int32_t) &&
                  kEiemBoneWeightSlotCount == 4,
              "EFFMESH BoneWeight layout changed");

static bool EiemValidateBoneWeightPayload(
    const EiemNativeMeshDocument &document, char *error, size_t errorSize) {
  if (document.skin.size() != (size_t)document.vertexCount ||
      document.bindPoses.empty()) {
    if (error) strncpy_s(error, errorSize,
                         "Native bone slots: skin/palette count is invalid",
                         _TRUNCATE);
    return false;
  }
  for (const BoneWeight &skin : document.skin) {
    const float weights[4] = {skin.weight0, skin.weight1,
                              skin.weight2, skin.weight3};
    const int32_t indices[4] = {skin.boneIndex0, skin.boneIndex1,
                                skin.boneIndex2, skin.boneIndex3};
    bool hasInfluence = false;
    for (int32_t slot = 0; slot < kEiemBoneWeightSlotCount; ++slot) {
      if (!std::isfinite(weights[slot]) || weights[slot] < 0.0f ||
          (weights[slot] > 0.0f &&
           (indices[slot] < 0 ||
            (size_t)indices[slot] >= document.bindPoses.size()))) {
        if (error) strncpy_s(error, errorSize,
                             "Native bone slots: invalid weight or bone index",
                             _TRUNCATE);
        return false;
      }
      hasInfluence |= weights[slot] > 0.0f;
    }
    if (!hasInfluence) {
      if (error) strncpy_s(error, errorSize,
                           "Native bone slots: vertex has no active influence",
                           _TRUNCATE);
      return false;
    }
  }
  return true;
}

// Keep native access in a scalar-only function: MSVC cannot compile SEH in a
// frame that unwinds C++ objects. No page-protection change or source write.
static bool EiemWriteBoneSlotField(uintptr_t native, int32_t width,
                                         int32_t *before, int32_t *after) {
  if (!native || (native + 0x1C8) % alignof(LONG) != 0 ||
      !before || !after) return false;
  __try {
    volatile LONG *field = reinterpret_cast<volatile LONG *>(native + 0x1C8);
    *before = (int32_t)InterlockedExchange(field, (LONG)width);
    *after = (int32_t)*field;
    return true;
  }
  __except (EXCEPTION_EXECUTE_HANDLER) { return false; }
}

static bool EiemSupportedNativeMeshLayout(void *mesh, uintptr_t *outNative) {
  if (outNative) *outNative = 0;
  HMODULE unity = GetModuleHandleW(L"UnityPlayer.dll");
  constexpr DWORD kTimestamp = 0x6A85914F;
  constexpr DWORD kImageSize = 0x208A000;
  constexpr uintptr_t kMeshVtableRva = 0x19C8230;
  if (!EiemUnityRvaIsMapped(unity, kMeshVtableRva, sizeof(void *)))
    return false;
  const uintptr_t base = reinterpret_cast<uintptr_t>(unity);
  bool versionMatches = false;
  __try {
    const auto *dos = reinterpret_cast<const IMAGE_DOS_HEADER *>(base);
    const auto *nt = reinterpret_cast<const IMAGE_NT_HEADERS *>(
        base + dos->e_lfanew);
    versionMatches = nt->FileHeader.TimeDateStamp == kTimestamp &&
                     nt->OptionalHeader.SizeOfImage == kImageSize;
  }
  __except (EXCEPTION_EXECUTE_HANDLER) { return false; }
  if (!versionMatches) return false;
  const uintptr_t native = reinterpret_cast<uintptr_t>(
      EiemGetNativeMeshPointer(mesh));
  if (!native || EiemReadNativePointerField(native, 0) !=
                     base + kMeshVtableRva)
    return false;
  if (outNative) *outNative = native;
  return true;
}

static bool EiemValidateNativeMeshBoneSlots(void *mesh, const char *stage,
                                               char *error, size_t errorSize) {
  if (!kEiemEnableNativeMeshBoneSlots) return true;
  uintptr_t native = 0;
  const int64_t getter = EiemReadNativeMeshScalar(
      s_eiemMeshGetBonesPerVertexValue, mesh);
  const bool layout = EiemSupportedNativeMeshLayout(mesh, &native);
  const int64_t actual = layout ? EiemReadNativeInt32Field(native, 0x1C8) : -1;
  if (layout && getter == kEiemBoneWeightSlotCount &&
      actual == kEiemBoneWeightSlotCount) return true;
  Log("[MESH-BONE-SLOTS] stage=%s mesh=%p native=%p layout=%d "
      "getter=%lld field=%lld expected=%d reject=1",
      stage ? stage : "unknown", mesh, (void *)native, layout ? 1 : 0,
      (long long)getter, (long long)actual, kEiemBoneWeightSlotCount);
  if (error) strncpy_s(error, errorSize,
                       "Native bone slots: native Mesh width validation failed",
                       _TRUNCATE);
  return false;
}

static bool EiemInitializeNativeMeshBoneSlots(
    void *mesh, void *templateMesh, const EiemNativeMeshDocument &document,
    const char *path, char *error, size_t errorSize) {
  if (!kEiemEnableNativeMeshBoneSlots || document.skin.empty())
    return true;
  // In-place and clone experiments are separate; never mutate the source.
  if (mesh == templateMesh ||
      !EiemValidateBoneWeightPayload(document, error, errorSize))
    return false;
  uintptr_t native = 0;
  const int64_t getter = EiemReadNativeMeshScalar(
      s_eiemMeshGetBonesPerVertexValue, mesh);
  if (getter != kEiemBoneWeightSlotCount ||
      !EiemSupportedNativeMeshLayout(mesh, &native)) {
    Log("[MESH-BONE-SLOTS] stage=prewrite mesh=%p native=%p path=%s "
        "getter=%lld expected=%d reject=1",
        mesh, (void *)native, path ? path : "<null>", (long long)getter,
        kEiemBoneWeightSlotCount);
    if (error) strncpy_s(error, errorSize,
                         "Native bone slots: getter or native layout mismatch",
                         _TRUNCATE);
    return false;
  }
  int32_t before = -1, after = -1;
  const bool wrote = EiemWriteBoneSlotField(
      native, kEiemBoneWeightSlotCount, &before, &after);
  if (kEiemEnableNativeMeshFlagProbe || !wrote || after != kEiemBoneWeightSlotCount)
    Log("[MESH-BONE-SLOTS] stage=postwrite mesh=%p native=%p path=%s "
      "getter=%lld width=%d before=%d after=%d wrote=%d",
      mesh, (void *)native, path ? path : "<null>", (long long)getter,
      kEiemBoneWeightSlotCount, before, after, wrote ? 1 : 0);
  if (!wrote || after != kEiemBoneWeightSlotCount) {
    if (error) strncpy_s(error, errorSize,
                         "Native bone slots: native write did not persist",
                         _TRUNCATE);
    return false;
  }
  return true;
}

// Static analysis identified UnityPlayer!0x4A90D0 as the only small native
// routine whose object layout matches Mesh and whose cold chunk writes native
// Mesh +0x1C8 after validating the inner skin-data object. Do not write the
// field directly: this probe calls the game's routine and records its effect.

// Snapshot the exact native Mesh objects already associated with replacement
// renderers after a low-frequency replay boundary. This catches a late game
// registration change that happens after the Mesh constructor/commit log,
// without installing a hot native hook or writing any field.

static uint64_t EiemMeshCacheStamp(uint64_t fileStamp) {
  // F10 is an explicit full resource rebuild. Keep ordinary lookups cached
  // within one published generation, while a new generation receives fresh
  // Unity Mesh objects even when the source file itself is unchanged. This is
  // intentional: F10 must re-submit new Mesh/Material state rather than reuse
  // the prior resource generation.
  const uint64_t generation = (uint64_t)(uint32_t)InterlockedCompareExchange(
      &s_eiemModGeneration, 0, 0);
  uint64_t stamp = fileStamp ^
      (generation + 0x9E3779B97F4A7C15ULL + (fileStamp << 6) +
       (fileStamp >> 2));
  stamp ^= stamp >> 30;
  stamp *= 0xBF58476D1CE4E5B9ULL;
  stamp ^= stamp >> 27;
  stamp *= 0x94D049BB133111EBULL;
  return stamp ^ (stamp >> 31);
}

static void EiemClearObjectResourceCache(
    std::vector<EiemObjectResourceCacheEntry> &cache, SRWLOCK *lock) {
  if (!lock) return;
  AcquireSRWLockExclusive(lock);
  cache.clear();
  ReleaseSRWLockExclusive(lock);
}

static void EiemClearNativeMeshResourceCache() {
  AcquireSRWLockExclusive(&s_eiemMeshResourceCacheLock);
  const size_t count = s_eiemMeshResourceCache.size();
  s_eiemMeshResourceCache.clear();
  ReleaseSRWLockExclusive(&s_eiemMeshResourceCacheLock);
  EiemClearObjectResourceCache(s_eiemMaterialResourceCache,
                               &s_eiemMaterialResourceCacheLock);
  EiemClearObjectResourceCache(s_eiemTextureResourceCache,
                               &s_eiemTextureResourceCacheLock);
  if (count)
    Log("[MOD] Released %zu generated mesh resource(s)", count);
}

static bool EiemBuildMeshResource(const EiemModRule &rule, void **outMesh,
                                  char *error, size_t errorSize,
                                  void *templateMesh = nullptr,
                                  std::shared_ptr<const EiemSkinIdentity> *skin = nullptr) {
  if (outMesh) *outMesh = nullptr;
  if (!EiemOnUnityThread()) {
    if (error) strncpy_s(error, errorSize, "Mesh construction requires Unity thread", _TRUNCATE);
    return false;
  }
  EiemModResource resource = {};
  if (!rule.hasMesh || !EiemFindModResource(rule.modPath, rule.mesh, "Mesh", &resource)) {
    if (error) strncpy_s(error, errorSize, "Render mesh section is not declared", _TRUNCATE);
    return false;
  }
  char fullPath[kEiemResourceDiskPathCapacity] = {};
  if (!EiemResolveResourceDiskPath(resource, fullPath, sizeof(fullPath))) {
    if (error) strncpy_s(error, errorSize,
                         "Mesh resource path is invalid or too long", _TRUNCATE);
    return false;
  }
#if defined(EIEM_NATIVE_MESH_ENTRY_REPLACE_BUILD)
  // A successful creation-entry replacement owns the source Mesh object.  Do
  // not build a second generated Mesh for the same renderer; return the
  // original object so all later consumers (including VFX) see the object
  // whose native finalizer was just run by the game.
  std::shared_ptr<EiemMeshSubmeshVisibilityState> entryVisibility;
  if (templateMesh &&
      EiemNativeMeshEntryLookupApplied(templateMesh, fullPath, skin,
                                       &entryVisibility)) {
    if (!EiemApplyMeshSubmeshVisibility(templateMesh, entryVisibility,
                                        rule.hiddenSubmeshMask, error,
                                        errorSize))
      return false;
    if (outMesh) *outMesh = templateMesh;
    if (s_eiemResourceDiagnostic)
      s_eiemResourceDiagnostic("mesh-entry-source", resource.modPath,
                               resource.section, templateMesh);
    Log("[MESH-ENTRY] render-reuse source=%p path=%s", templateMesh,
        fullPath);
    return true;
  }
#endif
#if defined(EIEM_NATIVE_MESH_INPLACE_PROBE_BUILD)
  // Diagnostic-only source Mesh experiment. Keep the game's native Mesh
  // object and apply the payload through the managed Mesh setters. The source
  // journal is captured first so F10 can restore the public channels and the
  // original BlendShape table before the next generation is replayed.
  if (!templateMesh) {
    if (error) strncpy_s(error, errorSize,
                         "In-place probe requires a source Mesh", _TRUNCATE);
    Log("[MESH-META-INPLACE-FAIL] path=%s reason=no-source-mesh",
        fullPath);
    return false;
  }
  char journalPath[384] = {};
  bool journalApplied = false;
  const bool journalExists =
      EiemNativeMeshSourceJournalInfo(templateMesh, journalPath,
                                      sizeof(journalPath), &journalApplied);
  if (journalExists && journalApplied) {
    if (_stricmp(journalPath, fullPath) != 0) {
      if (error) strncpy_s(error, errorSize,
                           "Source Mesh already has a different in-place rule",
                           _TRUNCATE);
      Log("[MESH-META-INPLACE-FAIL] source=%p path=%s existing=%s "
          "reason=conflicting-source-rule",
          templateMesh, fullPath, journalPath[0] ? journalPath : "<none>");
      return false;
    }
    if (outMesh) *outMesh = templateMesh;
    Log("[MESH-META-INPLACE] reuse source=%p path=%s generation=%ld",
        templateMesh, fullPath,
        (long)InterlockedCompareExchange(&s_eiemModGeneration, 0, 0));
    return true;
  }
  if (!EiemCaptureNativeMeshSourceJournal(templateMesh, fullPath)) {
    if (error) strncpy_s(error, errorSize,
                         "Unable to snapshot source Mesh before in-place write",
                         _TRUNCATE);
    Log("[MESH-META-INPLACE-FAIL] source=%p path=%s reason=journal-capture",
        templateMesh, fullPath);
    return false;
  }
  EiemNativeMeshSourceJournal journal;
  if (!EiemNativeMeshSourceJournalCopy(templateMesh, &journal)) {
    if (error) strncpy_s(error, errorSize,
                         "Source Mesh journal was not retained", _TRUNCATE);
    Log("[MESH-META-INPLACE-FAIL] source=%p path=%s "
        "reason=journal-not-retained", templateMesh, fullPath);
    return false;
  }
  if (journal.attemptFailed) {
    if (error) strncpy_s(error, errorSize,
                         "Source Mesh in-place attempt already failed",
                         _TRUNCATE);
    Log("[MESH-META-INPLACE-FAIL] source=%p path=%s "
        "reason=previous-inplace-attempt-failed", templateMesh, fullPath);
    return false;
  }
  if (!journal.publicSnapshotComplete) {
    if (error) strncpy_s(error, errorSize,
                         "Source Mesh CPU buffer is unreadable; unsafe to mutate",
                         _TRUNCATE);
    Log("[MESH-META-INPLACE-FAIL] source=%p path=%s "
        "reason=source-cpu-buffer-unreadable-no-safe-rollback",
        templateMesh, fullPath);
    EiemMarkNativeMeshSourceJournalFailed(templateMesh, fullPath);
    return false;
  }

  EiemNativeMeshDocument document;
  if (!EiemReadNativeMesh(fullPath, &document, error, errorSize)) {
    Log("[MESH-META-INPLACE-FAIL] source=%p path=%s reason=payload-read "
        "error=%s", templateMesh, fullPath,
        error && error[0] ? error : "unknown");
    return false;
  }
  std::shared_ptr<const EiemSkinIdentity> inplaceIdentity;
  if (!EiemBuildInPlaceSkinIdentity(document, &inplaceIdentity, error,
                                    errorSize)) {
    Log("[MESH-META-INPLACE-FAIL] source=%p path=%s reason=skin-identity "
        "error=%s", templateMesh, fullPath,
        error && error[0] ? error : "unknown");
    return false;
  }
  std::shared_ptr<EiemMeshSubmeshVisibilityState> inplaceVisibility;
  if (!EiemApplyNativeMeshDocumentInPlace(
          templateMesh, document, fullPath, &inplaceVisibility, error,
          errorSize)) {
    EiemMarkNativeMeshSourceJournalFailed(templateMesh, fullPath);
    return false;
  }
  if (!EiemApplyMeshSubmeshVisibility(
          templateMesh, inplaceVisibility, rule.hiddenSubmeshMask, error,
          errorSize)) {
    Log("[MESH-META-INPLACE-FAIL] source=%p path=%s "
        "reason=submesh-visibility error=%s",
        templateMesh, fullPath,
        error && error[0] ? error : "unknown");
    EiemMarkNativeMeshSourceJournalFailed(templateMesh, fullPath);
    return false;
  }
  if (!EiemMarkNativeMeshSourceJournalApplied(templateMesh, fullPath)) {
    if (error) strncpy_s(error, errorSize,
                         "Unable to mark source Mesh in-place journal",
                         _TRUNCATE);
    Log("[MESH-META-INPLACE-FAIL] source=%p path=%s reason=journal-mark",
        templateMesh, fullPath);
    return false;
  }
  if (skin) *skin = inplaceIdentity;
  if (outMesh) *outMesh = templateMesh;
  Log("[MESH-META-INPLACE] applied-direct-setters source=%p path=%s "
      "generation=%ld; renderer keeps original Mesh identity",
      templateMesh, fullPath,
      (long)InterlockedCompareExchange(&s_eiemModGeneration, 0, 0));
  return true;
#endif
  const uint64_t sourceStamp = EiemMeshResourceFileStamp(fullPath);
  const uint64_t fileStamp = EiemMeshCacheStamp(sourceStamp);
  // Native initialization is source-object specific.  Do not let the
  // modPath/section cache return a Mesh copied from source A for source B:
  // body, cloth and different LODs can carry different native state even
  // when they use the same exported replacement file.
  const uint64_t cacheVariant =
      templateMesh ? static_cast<uint64_t>(reinterpret_cast<uintptr_t>(templateMesh))
                   : 0;
  void *cachedMesh = nullptr;
  std::shared_ptr<const EiemSkinIdentity> cachedIdentity;
  std::shared_ptr<EiemMeshSubmeshVisibilityState> visibility;
  if (!EiemFindCachedObject(s_eiemMeshResourceCache, &s_eiemMeshResourceCacheLock,
                           resource.modPath, resource.section, fileStamp,
                           &cachedMesh, error, errorSize, &cachedIdentity,
                           cacheVariant,
                           &visibility)) return false;
  if (cachedMesh) {
    if (kEiemEnableNativeMeshBoneSlots && cachedIdentity &&
        !EiemValidateNativeMeshBoneSlots(cachedMesh, "cache-hit", error,
                                            errorSize))
      return false;
    if (!EiemApplyMeshSubmeshVisibility(cachedMesh, visibility,
                                        rule.hiddenSubmeshMask, error,
                                        errorSize))
      return false;
    if (kEiemEnableNativeMeshBoneSlots && cachedIdentity &&
        !EiemValidateNativeMeshBoneSlots(cachedMesh, "cache-visible", error,
                                            errorSize))
      return false;
    if (skin) *skin = cachedIdentity;
    if (s_eiemResourceDiagnostic) s_eiemResourceDiagnostic("mesh-cache-hit", resource.modPath, resource.section, cachedMesh);
    if (kEiemEnableLifecycleDiagnostics) Log("[DEBUG-hr1] mesh cache hit mod=%s section=%s mesh=%p",
        resource.modPath, resource.section, cachedMesh);
    if (outMesh) *outMesh = cachedMesh;
    return true;
  }

  std::shared_ptr<const EiemSkinIdentity> identity;
  void *mesh = EiemBuildNativeMesh(fullPath, templateMesh, error, errorSize,
                                   &identity, &visibility);
  if (!mesh) return false;
  if (!EiemCacheObject(s_eiemMeshResourceCache, &s_eiemMeshResourceCacheLock,
                       resource.modPath, resource.section, fileStamp, mesh,
                       error, errorSize, identity, cacheVariant,
                       visibility)) return false;
  if (!EiemApplyMeshSubmeshVisibility(mesh, visibility,
                                      rule.hiddenSubmeshMask, error,
                                      errorSize))
    return false;
  if (kEiemEnableNativeMeshBoneSlots && identity &&
      !EiemValidateNativeMeshBoneSlots(mesh, "mesh-built", error,
                                          errorSize))
    return false;
  if (skin) *skin = identity;
  if (outMesh) *outMesh = mesh;
  if (s_eiemResourceDiagnostic) s_eiemResourceDiagnostic("mesh-built", resource.modPath, resource.section, mesh);
  if (kEiemEnableLifecycleDiagnostics) Log("[DEBUG-hr1] mesh built mod=%s section=%s mesh=%p generation=%ld",
      resource.modPath, resource.section, mesh,
      InterlockedCompareExchange(&s_eiemModGeneration, 0, 0));
  return true;
}

static bool EiemResolveResourceDiskPath(const EiemModResource &resource,
                                        char *out, size_t outSize) {
  if (!out || outSize == 0 || !resource.modPath[0] ||
      !EiemModRelativeFilePath(resource.path)) return false;
  try {
    const auto path = std::filesystem::absolute(
        std::filesystem::u8path(resource.modPath).parent_path() /
        std::filesystem::u8path(resource.path)).lexically_normal().u8string();
    if (path.size() >= outSize) return false;
    memcpy(out, path.c_str(), path.size() + 1);
    return true;
  } catch (const std::exception &) { return false; }
}

static bool EiemReadMaterialFile(const char *path,
                                 std::vector<std::pair<std::string, std::string>> *out,
                                 char *error, size_t errorSize) {
  auto input = EiemOpenUtf8Input(path);
  if (!input) {
    if (error) strncpy_s(error, errorSize, "Unable to open EFF material file", _TRUNCATE);
    return false;
  }
  std::string line;
  bool formatSeen = false;
  while (std::getline(input, line)) {
    if (!line.empty() && line.back() == '\r') line.pop_back();
    const size_t first = line.find_first_not_of(" \t");
    if (first == std::string::npos || line[first] == ';' || line[first] == '#') continue;
    const size_t equals = line.find('=', first);
    if (equals == std::string::npos) continue;
    std::string key = line.substr(first, equals - first);
    std::string value = line.substr(equals + 1);
    const size_t keyEnd = key.find_last_not_of(" \t");
    const size_t valueFirst = value.find_first_not_of(" \t");
    const size_t valueEnd = value.find_last_not_of(" \t");
    if (keyEnd == std::string::npos) continue;
    key.resize(keyEnd + 1);
    value = valueFirst == std::string::npos ? "" : value.substr(valueFirst, valueEnd - valueFirst + 1);
    if (_stricmp(key.c_str(), "format") == 0) formatSeen = value == "EFFMAT";
    out->push_back({std::move(key), std::move(value)});
  }
  if (!formatSeen) {
    if (error) strncpy_s(error, errorSize, "Not an EFFMAT file", _TRUNCATE);
    return false;
  }
  return true;
}

// Return the shader texture property names declared by an EFFMAT resource.
// Unity's Shader property enumeration is not exported by every Endfield
// player build, while the material file already contains the authoritative
// mapping from shader property to EFF texture section.  Keeping this helper
// data-driven avoids embedding character or shader-specific property names in
// the native VFX adapter.
static bool EiemReadMaterialTexturePropertyNames(
    const EiemModRule &rule, const char *section,
    std::vector<std::string> *out, char *error, size_t errorSize) {
  if (out) out->clear();
  if (!section || !section[0] || !out) return false;
  EiemModResource resource = {};
  if (!EiemFindModResource(rule.modPath, section, "Material", &resource)) {
    if (error) strncpy_s(error, errorSize,
                         "Render material section is not declared", _TRUNCATE);
    return false;
  }
  char materialPath[kEiemResourceDiskPathCapacity] = {};
  if (!EiemResolveResourceDiskPath(resource, materialPath,
                                   sizeof(materialPath))) {
    if (error) strncpy_s(error, errorSize,
                         "Unable to resolve EFF material path", _TRUNCATE);
    return false;
  }
  std::vector<std::pair<std::string, std::string>> values;
  if (!EiemReadMaterialFile(materialPath, &values, error, errorSize))
    return false;
  for (const auto &pair : values) {
    if (_strnicmp(pair.first.c_str(), "texture.", 8) != 0 ||
        _strnicmp(pair.first.c_str(), "texture_scale.", 14) == 0 ||
        _strnicmp(pair.first.c_str(), "texture_offset.", 15) == 0)
      continue;
    const std::string property = pair.first.substr(8);
    if (property.empty()) continue;
    const bool duplicate = std::any_of(
        out->begin(), out->end(), [&](const std::string &existing) {
          return _stricmp(existing.c_str(), property.c_str()) == 0;
        });
    if (!duplicate) out->push_back(property);
  }
  return true;
}

static bool EiemBuildLzyTexturePropertyNamesForRule(
    const EiemModRule &rule,
    std::vector<std::vector<std::string>> *out, char *error,
    size_t errorSize) {
  if (out) out->clear();
  if (!out || rule.materialCount == 0) return true;
  uint32_t arrayCount = rule.materialCount;
  for (uint32_t i = 0; i < rule.materialCount; ++i) {
    if (rule.materialSlots[i] >= 0 &&
        (uint32_t)(rule.materialSlots[i] + 1) > arrayCount)
      arrayCount = (uint32_t)rule.materialSlots[i] + 1;
  }
  if (!arrayCount || arrayCount > 64) return false;
  out->resize(arrayCount);
  for (uint32_t index = 0; index < rule.materialCount; ++index) {
    const int32_t slot = rule.materialSlots[index] >= 0
                             ? rule.materialSlots[index]
                             : (int32_t)index;
    if (slot < 0 || (uint32_t)slot >= arrayCount) continue;
    std::vector<std::string> names;
    if (!EiemReadMaterialTexturePropertyNames(
            rule, rule.materials[index], &names, error, errorSize))
      return false;
    for (const std::string &name : names) {
      const bool duplicate = std::any_of(
          (*out)[slot].begin(), (*out)[slot].end(),
          [&](const std::string &existing) {
            return _stricmp(existing.c_str(), name.c_str()) == 0;
          });
      if (!duplicate) (*out)[slot].push_back(name);
    }
  }
  // Match EiemBuildRendererMaterials: unspecified slots inherit slot 0.
  for (uint32_t slot = 1; slot < arrayCount; ++slot)
    if ((*out)[slot].empty()) (*out)[slot] = (*out)[0];
  if (rule.submeshCount) {
    std::vector<std::vector<std::string>> original = *out;
    const uint32_t limit = rule.submeshCount < arrayCount
                               ? rule.submeshCount
                               : arrayCount;
    for (uint32_t submesh = 0; submesh < limit; ++submesh) {
      const int32_t sourceSlot = rule.submeshSlots[submesh];
      if (sourceSlot >= 0 && (uint32_t)sourceSlot < arrayCount)
        (*out)[submesh] = original[(size_t)sourceSlot];
    }
  }
  return true;
}

static uint64_t EiemMaterialDependencyStamp(
    const EiemModRule &rule, uint64_t materialStamp,
    const std::vector<std::pair<std::string, std::string>> &values) {
  // FNV-1a is sufficient here: this is a cache key, not an identity exposed
  // to users. Include every referenced texture file so a PNG-only edit
  // invalidates the cloned Material without rebuilding unrelated resources.
  uint64_t stamp = 1469598103934665603ull ^ materialStamp;
  for (const auto &pair : values) {
    if (_strnicmp(pair.first.c_str(), "texture.", 8) != 0 ||
        _strnicmp(pair.first.c_str(), "texture_scale.", 14) == 0 ||
        _strnicmp(pair.first.c_str(), "texture_offset.", 15) == 0)
      continue;
    EiemModResource texture = {};
    uint64_t dependency = 0;
    if (EiemFindModResource(rule.modPath, pair.second.c_str(), "Texture",
                            &texture)) {
      char path[kEiemResourceDiskPathCapacity] = {};
      if (EiemResolveResourceDiskPath(texture, path, sizeof(path)))
        dependency = EiemTextureDependencyStamp(
            texture, EiemMeshResourceFileStamp(path));
    }
    for (const unsigned char byte : pair.second) {
      stamp ^= byte;
      stamp *= 1099511628211ull;
    }
    stamp ^= dependency;
    stamp *= 1099511628211ull;
  }
  return stamp;
}

static void *EiemResolveResourceManagerInstance() {
  if (!s_eiemResourceManagerInstance && s_eiemResourceManagerGetInstance)
    s_eiemResourceManagerInstance =
        Invoke(s_eiemResourceManagerGetInstance, nullptr);
  return s_eiemResourceManagerInstance;
}

static void *EiemLoadOriginalAsset(const char *logicalPath, void *assetClass,
                                   char *error, size_t errorSize) {
  EiemResolveResourceManagerInstance();
  if (!logicalPath || !logicalPath[0] || !assetClass ||
      !s_eiemResourceManagerInstance || !s_eiemResourceManagerLoad ||
      !s_eiemProxyLoadImmediate || !s_eiemProxyGet ||
      !il2cpp_object_unbox) {
    if (error) strncpy_s(error, errorSize, "Game resource loader is unavailable", _TRUNCATE);
    return nullptr;
  }
  void *managedPath = il2cpp_string_new(logicalPath);
  void *type = il2cpp_type_get_object(il2cpp_class_get_type(assetClass));
  uint8_t category = 0;  // Beyond.Resource.RootCategory.Main
  void *params[] = {managedPath, type, &category};
  void *handle = Invoke(s_eiemResourceManagerLoad,
                        s_eiemResourceManagerInstance, params);
  if (!handle) {
    if (error) strncpy_s(error, errorSize, "Game resource loader returned no handle", _TRUNCATE);
    return nullptr;
  }
  // BundleResourceManager.Load returns the value type FAssetProxyHandle.
  // il2cpp_runtime_invoke boxes value-type return values; its instance methods
  // require the address of the unboxed payload, not the Il2CppObject header.
  // Do not replace this with a fixed object-header offset: the exported IL2CPP
  // API is the authoritative ABI boundary.
  void *unboxedHandle = il2cpp_object_unbox(handle);
  if (!unboxedHandle) {
    if (error)
      strncpy_s(error, errorSize,
                "Game resource loader returned an invalid value-type handle",
                _TRUNCATE);
    return nullptr;
  }
  Invoke(s_eiemProxyLoadImmediate, unboxedHandle);
  void *asset = Invoke(s_eiemProxyGet, unboxedHandle);
  if (!asset && error)
    strncpy_s(error, errorSize, "Game resource loader could not resolve source path", _TRUNCATE);
  return asset;
}

static bool EiemParseColor(const std::string &text, Color *out) {
  if (!out) return false;
  return sscanf_s(text.c_str(), "%f,%f,%f,%f", &out->r, &out->g, &out->b, &out->a) == 4;
}

static bool EiemParseVector2(const std::string &text, Vector2 *out) {
  if (!out) return false;
  return sscanf_s(text.c_str(), "%f,%f", &out->x, &out->y) == 2;
}

static bool EiemParseFloat(const std::string &text, float *out) {
  if (!out || text.empty()) return false;
  char *end = nullptr;
  const float value = strtof(text.c_str(), &end);
  if (end == text.c_str() || !end || *end != '\0') return false;
  *out = value;
  return true;
}

static bool EiemParseInt32(const std::string &text, int32_t *out) {
  if (!out || text.empty()) return false;
  char *end = nullptr;
  const long value = strtol(text.c_str(), &end, 10);
  if (end == text.c_str() || !end || *end != '\0' ||
      value < INT32_MIN || value > INT32_MAX)
    return false;
  *out = (int32_t)value;
  return true;
}

static uint64_t EiemTextureDependencyStamp(const EiemModResource &resource,
                                           uint64_t fileStamp) {
  uint64_t stamp = 1469598103934665603ull ^ fileStamp;
  const auto mix = [&stamp](uint64_t value) {
    stamp ^= value;
    stamp *= 1099511628211ull;
  };
  mix(resource.textureLinear ? 1u : 0u);
  mix(resource.textureMipmaps ? 1u : 0u);
  mix((uint32_t)resource.textureFilter);
  mix((uint32_t)resource.textureWrap);
  mix((uint32_t)resource.textureAniso);
  uint32_t biasBits = 0;
  memcpy(&biasBits, &resource.textureMipBias, sizeof(biasBits));
  mix(biasBits);
  return stamp;
}

static bool EiemBuildTextureResource(const EiemModRule &rule, const char *section,
                                     void **outTexture, char *error,
                                     size_t errorSize) {
  if (outTexture) *outTexture = nullptr;
  if (!section || !section[0] || !s_eiemTexture2DClass || !s_eiemByteClass ||
      !s_eiemTexture2DCtor || !s_eiemImageLoad) {
    if (error) strncpy_s(error, errorSize, "Unity PNG texture APIs are unavailable", _TRUNCATE);
    return false;
  }
  EiemModResource resource = {};
  if (!EiemFindModResource(rule.modPath, section, "Texture", &resource)) {
    if (error) strncpy_s(error, errorSize, "Material texture section is not declared", _TRUNCATE);
    return false;
  }
  char texturePath[kEiemResourceDiskPathCapacity] = {};
  if (!EiemResolveResourceDiskPath(resource, texturePath, sizeof(texturePath))) {
    if (error) strncpy_s(error, errorSize, "Unable to resolve EFF texture path", _TRUNCATE);
    return false;
  }
  const uint64_t fileStamp = EiemTextureDependencyStamp(
      resource, EiemMeshResourceFileStamp(texturePath));
  void *cachedTexture = nullptr;
  if (!EiemFindCachedObject(s_eiemTextureResourceCache, &s_eiemTextureResourceCacheLock,
                           resource.modPath, resource.section, fileStamp,
                           &cachedTexture, error, errorSize)) return false;
  if (cachedTexture) {
    if (s_eiemResourceDiagnostic) s_eiemResourceDiagnostic("texture-cache-hit", resource.modPath, resource.section, cachedTexture);
    if (outTexture) *outTexture = cachedTexture;
    return true;
  }
  auto input = EiemOpenUtf8Input(texturePath, std::ios::binary | std::ios::ate);
  if (!input) {
    if (error) strncpy_s(error, errorSize, "Unable to open external texture", _TRUNCATE);
    return false;
  }
  const std::streamoff length = input.tellg();
  if (length <= 0 || length > 512ll * 1024 * 1024) {
    if (error) strncpy_s(error, errorSize, "External texture size is invalid", _TRUNCATE);
    return false;
  }
  std::vector<uint8_t> bytes((size_t)length);
  input.seekg(0, std::ios::beg);
  input.read((char *)bytes.data(), length);
  if (!input.good()) {
    if (error) strncpy_s(error, errorSize, "Unable to read external texture", _TRUNCATE);
    return false;
  }
  void *managedBytes = il2cpp_array_new(s_eiemByteClass, bytes.size());
  if (!managedBytes) {
    if (error) strncpy_s(error, errorSize, "Unable to allocate managed PNG buffer", _TRUNCATE);
    return false;
  }
  memcpy((char *)managedBytes + IL2CPP_ARRAY_DATA, bytes.data(), bytes.size());
  void *texture = il2cpp_object_new(s_eiemTexture2DClass);
  if (!texture) {
    if (error) strncpy_s(error, errorSize, "Unable to allocate Unity Texture2D", _TRUNCATE);
    return false;
  }
  int32_t width = 2, height = 2;
  int32_t format = 4;  // UnityEngine.TextureFormat.RGBA32
  bool mipmaps = resource.textureMipmaps;
  bool linear = resource.textureLinear;
  void *ctorParams[] = {&width, &height, &format, &mipmaps, &linear};
  Invoke(s_eiemTexture2DCtor, texture, ctorParams);
  bool markNonReadable = true;
  void *loadParams[] = {texture, managedBytes, &markNonReadable};
  void *result = Invoke(s_eiemImageLoad, nullptr, loadParams);
  const bool decoded = result && *(bool *)((char *)result + 16);
  if (!decoded) {
    if (error) strncpy_s(error, errorSize, "Unity failed to decode external PNG", _TRUNCATE);
    return false;
  }
  if (!s_eiemTextureSetFilterMode || !s_eiemTextureSetWrapMode ||
      !s_eiemTextureSetAnisoLevel || !s_eiemTextureSetMipMapBias) {
    if (error) strncpy_s(error, errorSize, "Unity texture sampler APIs are unavailable", _TRUNCATE);
    return false;
  }
  if (resource.textureFilter < 0 || resource.textureFilter > 2 ||
      resource.textureWrap < 0 || resource.textureWrap > 3 ||
      resource.textureAniso < 0 || resource.textureAniso > 16) {
    if (error) strncpy_s(error, errorSize, "EFF texture sampler values are invalid", _TRUNCATE);
    return false;
  }
  int32_t filter = resource.textureFilter;
  int32_t wrap = resource.textureWrap;
  int32_t aniso = resource.textureAniso;
  float mipBias = resource.textureMipBias;
  void *filterParams[] = {&filter};
  void *wrapParams[] = {&wrap};
  void *anisoParams[] = {&aniso};
  void *biasParams[] = {&mipBias};
  Invoke(s_eiemTextureSetFilterMode, texture, filterParams);
  Invoke(s_eiemTextureSetWrapMode, texture, wrapParams);
  Invoke(s_eiemTextureSetAnisoLevel, texture, anisoParams);
  Invoke(s_eiemTextureSetMipMapBias, texture, biasParams);
  if (s_eiemObjectSetName) {
    void *name = il2cpp_string_new(resource.targetAsset[0]
                                       ? resource.targetAsset
                                       : resource.section);
    void *nameParams[] = {name};
    Invoke(s_eiemObjectSetName, texture, nameParams);
  }
  if (!EiemCacheObject(s_eiemTextureResourceCache, &s_eiemTextureResourceCacheLock,
                       resource.modPath, resource.section, fileStamp, texture,
                       error, errorSize)) return false;
  if (outTexture) *outTexture = texture;
  if (s_eiemResourceDiagnostic) s_eiemResourceDiagnostic("texture-built", resource.modPath, resource.section, texture);
  return true;
}

// Name every property the source material's shader exposes, with its type.
// A material file can request this with `dump_properties=true` so a hide or fade
// property can be identified from real data rather than guessed; guessing is
// unsafe because `Material.SetFloat` on a name the shader does not declare is a
// silent no-op.
static void EiemLogShaderProperties(void *material, const char *section) {
  if (!material || !g_material_get_shader || !g_eiemShaderGetPropertyCount ||
      !g_eiemShaderGetPropertyName || !g_eiemShaderGetPropertyType) {
    Log("[MAT-DUMP] section=%s unavailable: shader introspection APIs missing "
        "getShader=%p count=%p name=%p type=%p",
        section ? section : "<unknown>", g_material_get_shader,
        g_eiemShaderGetPropertyCount, g_eiemShaderGetPropertyName,
        g_eiemShaderGetPropertyType);
    return;
  }
  void *shader = Invoke(g_material_get_shader, material);
  if (!shader) {
    Log("[MAT-DUMP] section=%s material has no shader", section ? section : "<unknown>");
    return;
  }
  // Material.get_shader returns a boxed Int32 for a zero-argument method.
  auto unboxInt = [](void *boxed) -> int32_t {
    __try { return boxed ? *(int32_t *)((char *)boxed + 16) : -1; }
    __except (1) { return -1; }
  };
  const int32_t count = unboxInt(Invoke(g_eiemShaderGetPropertyCount, shader));
  if (count <= 0 || count > 512) {
    Log("[MAT-DUMP] section=%s propertyCount=%d", section ? section : "<unknown>", count);
    return;
  }
  char names[768] = {};
  size_t used = 0;
  for (int32_t index = 0; index < count; ++index) {
    void *indexParams[] = {&index};
    void *nameObject = Invoke(g_eiemShaderGetPropertyName, shader, indexParams);
    void *typeObject = Invoke(g_eiemShaderGetPropertyType, shader, indexParams);
    char name[192] = {};
    if (nameObject) ReadStrUtf8(nameObject, name, sizeof(name));
    if (!name[0]) continue;
    const int32_t type = unboxInt(typeObject);
    const int written = snprintf(names + used, sizeof(names) - used, "%s%s:%d",
                                 used ? " " : "", name, type);
    if (written <= 0 || (size_t)written >= sizeof(names) - used) break;
    used += (size_t)written;
  }
  Log("[MAT-DUMP] section=%s properties=%d [%s]",
      section ? section : "<unknown>", count, names);
}

static bool EiemBuildMaterialResource(const EiemModRule &rule, const char *section,
                                      void **outMaterial, char *error,
                                      size_t errorSize) {
  if (outMaterial) *outMaterial = nullptr;
  EiemModResource resource = {};
  if (!section || !section[0] ||
      !EiemFindModResource(rule.modPath, section, "Material", &resource)) {
    if (error) strncpy_s(error, errorSize, "Render material section is not declared", _TRUNCATE);
    return false;
  }
  char materialPath[kEiemResourceDiskPathCapacity] = {};
  if (!EiemResolveResourceDiskPath(resource, materialPath, sizeof(materialPath))) {
    if (error) strncpy_s(error, errorSize, "Unable to resolve EFF material path", _TRUNCATE);
    return false;
  }
  const uint64_t fileStamp = EiemMeshResourceFileStamp(materialPath);
  std::vector<std::pair<std::string, std::string>> values;
  if (!EiemReadMaterialFile(materialPath, &values, error, errorSize)) return false;
  const uint64_t dependencyStamp =
      EiemMaterialDependencyStamp(rule, fileStamp, values);
  void *cachedMaterial = nullptr;
  if (!EiemFindCachedObject(s_eiemMaterialResourceCache, &s_eiemMaterialResourceCacheLock,
                           resource.modPath, resource.section, dependencyStamp,
                           &cachedMaterial, error, errorSize)) return false;
  // Resolve configured textures even on a Material cache hit. A native texture
  // may have expired/rebuilt without any disk timestamp changing.
  std::vector<std::pair<std::string, void *>> textures;
  for (const auto &pair : values) {
    if (_strnicmp(pair.first.c_str(), "texture.", 8) != 0) continue;
    if (!s_eiemMaterialSetTexture || !s_eiemMaterialGetTexture) {
      if (error) strncpy_s(error, errorSize, "Unity Material texture APIs are unavailable", _TRUNCATE);
      return false;
    }
    void *texture = nullptr;
    if (!EiemBuildTextureResource(rule, pair.second.c_str(), &texture, error, errorSize))
      return false;
    textures.emplace_back(pair.first.substr(8), texture);
  }
  for (const auto &texture : textures) {
    if (!cachedMaterial) break;
    void *name = il2cpp_string_new(texture.first.c_str());
    void *params[] = {name};
    if (Invoke(s_eiemMaterialGetTexture, cachedMaterial, params) != texture.second) {
      Log("[MOD-CACHE] rebuild material mod=%s section=%s reason=texture binding changed",
          resource.modPath, resource.section);
      cachedMaterial = nullptr;
    }
  }
  if (cachedMaterial) {
    if (s_eiemResourceDiagnostic) s_eiemResourceDiagnostic("material-cache-hit", resource.modPath, resource.section, cachedMaterial);
    if (outMaterial) *outMaterial = cachedMaterial;
    return true;
  }
  std::string source;
  bool dumpProperties = false;
  for (const auto &pair : values) {
    if (_stricmp(pair.first.c_str(), "source") == 0) source = pair.second;
    if (_stricmp(pair.first.c_str(), "dump_properties") == 0)
      dumpProperties = pair.second == "true" || pair.second == "1";
  }
  if (source.empty()) {
    if (error) strncpy_s(error, errorSize, "EFF material has no source logical path", _TRUNCATE);
    return false;
  }
  void *sourceMaterial = EiemLoadOriginalAsset(
      source.c_str(), s_eiemMaterialClass, error, errorSize);
  if (!sourceMaterial || !s_eiemMaterialClass || !s_eiemMaterialCtorCopy) return false;
  if (EiemNativeObjectStatus(sourceMaterial) != 1) {
    if (error) strncpy_s(error, errorSize, "Source Material is not natively valid", _TRUNCATE);
    return false;
  }
  void *material = il2cpp_object_new(s_eiemMaterialClass);
  if (!material) {
    if (error) strncpy_s(error, errorSize, "Unable to allocate Unity Material", _TRUNCATE);
    return false;
  }
  void *copyParams[] = {sourceMaterial};
  Invoke(s_eiemMaterialCtorCopy, material, copyParams);
  if (dumpProperties) {
    // Name the source material's properties instead of guessing at a hide/fade
    // property. A `float.` entry that does not exist on the shader is silently
    // ignored by Unity, so without this a wrong name looks exactly like a
    // property that had no visible effect.
    EiemLogShaderProperties(sourceMaterial, resource.section);
  }
  size_t textureIndex = 0;
  for (const auto &pair : values) {
    const char *key = pair.first.c_str();
    const char *value = pair.second.c_str();
    if (_strnicmp(key, "float.", 6) == 0) {
      if (!s_eiemMaterialSetFloat) {
        if (error) strncpy_s(error, errorSize, "Unity Material.SetFloat is unavailable", _TRUNCATE);
        return false;
      }
      float scalar = 0.0f;
      if (!EiemParseFloat(pair.second, &scalar)) {
        if (error) strncpy_s(error, errorSize, "Invalid EFF material float", _TRUNCATE);
        return false;
      }
      void *name = il2cpp_string_new(key + 6);
      void *params[] = {name, &scalar};
      Invoke(s_eiemMaterialSetFloat, material, params);
    } else if (_strnicmp(key, "int.", 4) == 0) {
      if (!s_eiemMaterialSetInt) {
        if (error) strncpy_s(error, errorSize, "Unity Material.SetInt is unavailable", _TRUNCATE);
        return false;
      }
      int32_t integer = 0;
      if (!EiemParseInt32(pair.second, &integer)) {
        if (error) strncpy_s(error, errorSize, "Invalid EFF material int", _TRUNCATE);
        return false;
      }
      void *name = il2cpp_string_new(key + 4);
      void *params[] = {name, &integer};
      Invoke(s_eiemMaterialSetInt, material, params);
    } else if (_strnicmp(key, "value4.", 7) == 0) {
      if (!s_eiemMaterialSetColor) {
        if (error) strncpy_s(error, errorSize, "Unity Material.SetColor is unavailable", _TRUNCATE);
        return false;
      }
      Color color = {};
      if (!EiemParseColor(pair.second, &color)) {
        if (error) strncpy_s(error, errorSize, "Invalid EFF material value4", _TRUNCATE);
        return false;
      }
      void *name = il2cpp_string_new(key + 7);
      void *params[] = {name, &color};
      Invoke(s_eiemMaterialSetColor, material, params);
    } else if (_strnicmp(key, "texture_scale.", 14) == 0) {
      if (!s_eiemMaterialSetTextureScale || !s_eiemVector2Class) {
        if (error) strncpy_s(error, errorSize, "Unity Material.SetTextureScale is unavailable", _TRUNCATE);
        return false;
      }
      Vector2 scale = {};
      if (!EiemParseVector2(pair.second, &scale)) {
        if (error) strncpy_s(error, errorSize, "Invalid EFF material texture scale", _TRUNCATE);
        return false;
      }
      void *name = il2cpp_string_new(key + 14);
      void *params[] = {name, &scale};
      Invoke(s_eiemMaterialSetTextureScale, material, params);
    } else if (_strnicmp(key, "texture_offset.", 15) == 0) {
      if (!s_eiemMaterialSetTextureOffset || !s_eiemVector2Class) {
        if (error) strncpy_s(error, errorSize, "Unity Material.SetTextureOffset is unavailable", _TRUNCATE);
        return false;
      }
      Vector2 offset = {};
      if (!EiemParseVector2(pair.second, &offset)) {
        if (error) strncpy_s(error, errorSize, "Invalid EFF material texture offset", _TRUNCATE);
        return false;
      }
      void *name = il2cpp_string_new(key + 15);
      void *params[] = {name, &offset};
      Invoke(s_eiemMaterialSetTextureOffset, material, params);
    } else if (_strnicmp(key, "texture.", 8) == 0) {
      void *texture = textures[textureIndex++].second;
      void *name = il2cpp_string_new(key + 8);
      void *params[] = {name, texture};
      Invoke(s_eiemMaterialSetTexture, material, params);
      void *getParams[] = {name};
      if (Invoke(s_eiemMaterialGetTexture, material, getParams) != texture) {
        if (error) strncpy_s(error, errorSize, "Unity Material texture read-back failed", _TRUNCATE);
        return false;
      }
    }
  }
  if (!EiemCacheObject(s_eiemMaterialResourceCache, &s_eiemMaterialResourceCacheLock,
                       resource.modPath, resource.section, dependencyStamp, material,
                       error, errorSize)) return false;
  if (outMaterial) *outMaterial = material;
  if (s_eiemResourceDiagnostic) s_eiemResourceDiagnostic("material-built", resource.modPath, resource.section, material);
  return true;
}

static void EiemApplySubmeshMaterialMap(const EiemModRule &rule,
                                        void **items, uint32_t count) {
  if (!items || count == 0 || rule.submeshCount == 0) return;
  std::vector<void *> original(items, items + count);
  const uint32_t limit = rule.submeshCount < count ? rule.submeshCount : count;
  for (uint32_t submesh = 0; submesh < limit; ++submesh) {
    const int32_t sourceSlot = rule.submeshSlots[submesh];
    if (sourceSlot >= 0 && (uint32_t)sourceSlot < count)
      items[submesh] = original[(size_t)sourceSlot];
  }
}

static bool EiemBuildRendererMaterials(const EiemModRule &rule, void **outArray,
                                       char *error, size_t errorSize) {
  if (outArray) *outArray = nullptr;
  if (rule.materialCount == 0) return true;
  if (!s_eiemMaterialClass) {
    if (error) strncpy_s(error, errorSize, "Unity Material class is unavailable", _TRUNCATE);
    return false;
  }
  uint32_t arrayCount = rule.materialCount;
  for (uint32_t i = 0; i < rule.materialCount; ++i) {
    if (rule.materialSlots[i] >= 0 &&
        (uint32_t)(rule.materialSlots[i] + 1) > arrayCount)
      arrayCount = (uint32_t)rule.materialSlots[i] + 1;
  }
  void *array = il2cpp_array_new(s_eiemMaterialClass, arrayCount);
  if (!array) {
    if (error) strncpy_s(error, errorSize, "Unable to allocate Unity Material array", _TRUNCATE);
    return false;
  }
  void **items = (void **)((char *)array + IL2CPP_ARRAY_DATA);
  for (uint32_t index = 0; index < rule.materialCount; ++index) {
    const int32_t slot = rule.materialSlots[index] >= 0
                             ? rule.materialSlots[index]
                             : (int32_t)index;
    if (!EiemBuildMaterialResource(rule, rule.materials[index], &items[slot], error, errorSize))
      return false;
  }
  // Same rule as the sourced path: a slot the Mesh needs but the config does not
  // declare must not stay null, or Unity draws that submesh with the magenta
  // error shader.
  if (arrayCount > 0 && rule.materialCount > 0)
    for (uint32_t slot = 0; slot < arrayCount; ++slot)
      if (!items[slot]) items[slot] = items[0];
  EiemApplySubmeshMaterialMap(rule, items, arrayCount);
  if (outArray) *outArray = array;
  return true;
}

static bool EiemBuildRendererMaterialsForSource(const EiemModRule &rule,
                                                void *sourceRenderer,
                                                void **outArray, char *error,
                                                size_t errorSize) {
  if (outArray) *outArray = nullptr;
  if (!sourceRenderer || !g_renderer_get_sharedMaterials)
    return EiemBuildRendererMaterials(rule, outArray, error, errorSize);
  void *sourceMaterials = Invoke(g_renderer_get_sharedMaterials, sourceRenderer);
  const int sourceCount = sourceMaterials ? *(int *)((char *)sourceMaterials + 24) : 0;
  int requiredCount = sourceCount;
  for (uint32_t i = 0; i < rule.materialCount; ++i) {
    const int slot = rule.materialSlots[i] >= 0 ? rule.materialSlots[i] : (int)i;
    if (slot + 1 > requiredCount) requiredCount = slot + 1;
  }
  if (rule.submeshCount > (uint32_t)requiredCount)
    requiredCount = (int)rule.submeshCount;
  if (requiredCount <= 0) return true;
  if (!s_eiemMaterialClass) {
    if (error) strncpy_s(error, errorSize, "Unity Material class is unavailable", _TRUNCATE);
    return false;
  }
  void *array = il2cpp_array_new(s_eiemMaterialClass, (size_t)requiredCount);
  if (!array) {
    if (error) strncpy_s(error, errorSize, "Unable to allocate Unity Material array", _TRUNCATE);
    return false;
  }
  void **items = (void **)((char *)array + IL2CPP_ARRAY_DATA);
  if (sourceMaterials && sourceCount > 0)
    memcpy(items, (char *)sourceMaterials + IL2CPP_ARRAY_DATA,
           (size_t)sourceCount * sizeof(void *));
  // A submesh count above the source's material count only happens when the
  // replacement Mesh carries more submeshes than the source Renderer had
  // materials -- typically a merged Mesh whose submeshes are the sibling parts.
  // The slots we do not declare must not be left null: a null slot makes Unity
  // draw that submesh with no material, which shows as the magenta error
  // shader. Before the parts were merged each part was its own Renderer and its
  // first slot received the source's primary material, so extending that
  // material across the undeclared slots reproduces the previous appearance
  // instead of inventing one.
  if (sourceMaterials && sourceCount > 0)
    for (int slot = sourceCount; slot < requiredCount; ++slot)
      items[slot] = items[0];
  for (uint32_t i = 0; i < rule.materialCount; ++i) {
    const int slot = rule.materialSlots[i] >= 0 ? rule.materialSlots[i] : (int)i;
    if (!EiemBuildMaterialResource(rule, rule.materials[i], &items[slot],
                                   error, errorSize))
      return false;
  }
  EiemApplySubmeshMaterialMap(rule, items, (uint32_t)requiredCount);
  if (outArray) *outArray = array;
  return true;
}
